#!/usr/bin/env node
/* =====================================================================
   tools/build.js — turns web/ into things you can actually play.

     node tools/build.js

   makes:
     docs/index.html            one self-contained file (open it in any browser,
                                or turn on GitHub Pages for the docs/ folder)
     Hearth.swiftpm/GameHTML.swift   the same file, inside the iPad app
   ===================================================================== */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const WEB = path.join(ROOT, "web");
const read = p => fs.readFileSync(path.join(WEB, p), "utf8");

let html = read("index.html");

// 1. the stylesheet, with the font baked in as base64
const font = fs.readFileSync(path.join(WEB, "assets/vt323.woff2")).toString("base64");
const css = read("style.css").replace('url("assets/vt323.woff2")', 'url("data:font/woff2;base64,' + font + '")');
html = html.replace(/<!-- @@STYLE@@ -->[\s\S]*?<!-- @@\/STYLE@@ -->/, () => "<style>\n" + css + "\n</style>");

// 2. every script, in the order index.html lists them
const scripts = [...html.match(/<!-- @@SCRIPTS@@ -->([\s\S]*?)<!-- @@\/SCRIPTS@@ -->/)[1].matchAll(/src="([^"]+)"/g)].map(m => m[1]);
const js = scripts.map(s => "/* ---- " + s + " ---- */\n" + read(s)).join("\n");
if (js.includes("</script")) throw new Error("a script contains </script — that would end the inline block early");
html = html.replace(/<!-- @@SCRIPTS@@ -->[\s\S]*?<!-- @@\/SCRIPTS@@ -->/, () => "<script>\n" + js + "\n</script>");

// 3. write it out
fs.mkdirSync(path.join(ROOT, "docs"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "docs/index.html"), html);

if (html.includes('"""###')) throw new Error('the game contains """### which would break the Swift raw string');
const swift = "// Auto-generated by tools/build.js from web/. Don't edit by hand — edit web/ and rebuild.\n" +
  "let GAME_HTML = ###\"\"\"\n" + html + "\n\"\"\"###\n";
fs.writeFileSync(path.join(ROOT, "Hearth.swiftpm/GameHTML.swift"), swift);

const kb = n => (n / 1024).toFixed(0) + " KB";
console.log("built " + scripts.length + " scripts →");
console.log("  docs/index.html                 " + kb(html.length));
console.log("  Hearth.swiftpm/GameHTML.swift   " + kb(swift.length));
